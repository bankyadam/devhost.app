import { join } from 'node:path';
import type { Executor } from '../runner/executor.js';
import { launchDaemonsDir, plistPath, stagedPlistPath } from '../launchd.js';

/**
 * The work volume's root operations (spec A7.12). With the root helper they are its named
 * operations; without it, the same commands through sudo (announced, listed in --dry-run).
 */
export const UNLOCK_LABEL = 'com.devhost.storage.unlock';
export const PASSPHRASE_SERVICE = 'devhost.workvolume';
export const SYSTEM_KEYCHAIN = '/Library/Keychains/System.keychain';
export const AUTODISKMOUNT = '/Library/Preferences/SystemConfiguration/autodiskmount';

const UUID = /^[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}$/;
const checkUuid = (uuid: string): string => {
  if (!UUID.test(uuid)) throw new Error(`"${uuid}" is not an APFS volume UUID`);
  return uuid;
};

export const enableOwnership = (exec: Executor, uuid: string): Promise<unknown> =>
  exec.rootOp({ helper: ['enable-ownership', checkUuid(uuid)], fallback: [{ command: 'diskutil', args: ['enableOwnership', uuid] }], reason: 'make the work volume honor file owners (git, ssh and file modes need it)' });

export const spotlightOff = (exec: Executor, mountPoint: string): Promise<unknown> =>
  exec.rootOp({ helper: ['spotlight-off', mountPoint], fallback: [{ command: 'mdutil', args: ['-i', 'off', mountPoint] }], reason: 'turn Spotlight indexing off on the work volume' });

export const automountWithoutLogin = (exec: Executor): Promise<unknown> =>
  exec.rootOp({
    helper: ['automount-without-login'],
    fallback: [{ command: 'defaults', args: ['write', AUTODISKMOUNT, 'AutomountDisksWithoutUserLogin', '-bool', 'true'] }],
    reason: 'mount external volumes at boot, before anyone logs in',
  });

/**
 * The unlock daemon's script: only when the volume is present but not mounted, the passphrase goes
 * from the System keychain through a pipe into diskutil. The root helper builds the same plist
 * itself (templates/devhost-root.js); this copy is for installing it with sudo.
 */
export const unlockScript = (): string =>
  'if [ -z "$(/usr/sbin/diskutil info -plist "$0" 2>/dev/null | /usr/bin/plutil -extract MountPoint raw - 2>/dev/null)" ] && /usr/sbin/diskutil info "$0" >/dev/null 2>&1; then ' +
  `/usr/bin/security find-generic-password -s ${PASSPHRASE_SERVICE} -a devhost -w ${SYSTEM_KEYCHAIN} | /usr/bin/tr -d '\\n' | /usr/sbin/diskutil apfs unlockVolume "$0" -stdinpassphrase >/dev/null 2>&1; fi; exit 0`;

const xml = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function unlockPlist(uuid: string): string {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<!-- Generated by devhost (storage.workVolume.encrypted). Runs as root: unlocks the work volume at boot. -->',
    '<plist version="1.0">',
    '<dict>',
    `  <key>Label</key>\n  <string>${UNLOCK_LABEL}</string>`,
    '  <key>ProgramArguments</key>',
    '  <array>',
    ...['/bin/sh', '-c', unlockScript(), checkUuid(uuid)].map((a) => `    <string>${xml(a)}</string>`),
    '  </array>',
    '  <key>RunAtLoad</key>\n  <true/>',
    '  <key>KeepAlive</key>\n  <true/>',
    '  <key>ThrottleInterval</key>\n  <integer>30</integer>',
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

export async function installUnlockDaemon(exec: Executor, home: string, uuid: string): Promise<void> {
  const staged = stagedPlistPath(home, UNLOCK_LABEL);
  const dest = plistPath(UNLOCK_LABEL);
  // Staged for the sudo path; the helper builds its own copy from the UUID.
  await exec.writeText(staged, unlockPlist(uuid), { description: `stage ${staged}` });
  await exec.rootOp({
    helper: ['unlock-daemon', checkUuid(uuid)],
    fallback: [
      { command: 'launchctl', args: ['bootout', `system/${UNLOCK_LABEL}`] },
      { command: 'install', args: ['-m', '644', '-o', 'root', '-g', 'wheel', staged, dest] },
      { command: 'launchctl', args: ['bootstrap', 'system', dest] },
    ],
    reason: 'install the root service that unlocks the encrypted work volume at boot',
    allowFailure: false,
  });
}

export const removeUnlockDaemon = (exec: Executor): Promise<unknown> =>
  exec.rootOp({
    helper: ['unlock-daemon-remove'],
    fallback: [
      { command: 'launchctl', args: ['bootout', `system/${UNLOCK_LABEL}`] },
      { command: 'rm', args: ['-f', plistPath(UNLOCK_LABEL)] },
    ],
    reason: 'remove the work volume unlock service',
    allowFailure: true,
  });

/** The passphrase into the System keychain, through stdin only (never an argument, the plan or a log). */
export function setPassphrase(exec: Executor, passphrase: string): Promise<unknown> {
  if (passphrase === '' || /[\r\n]/.test(passphrase)) throw new Error('the passphrase is one non-empty line');
  const quoted = passphrase.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return exec.rootOp({
    helper: ['set-passphrase'],
    input: `${passphrase}\n`,
    fallback: [{ command: 'security', args: ['-i'], input: `add-generic-password -U -a devhost -s ${PASSPHRASE_SERVICE} -l "devhost work volume" -w "${quoted}" ${SYSTEM_KEYCHAIN}\n` }],
    reason: 'store the work volume passphrase in the System keychain',
  });
}

export const removePassphrase = (exec: Executor): Promise<unknown> =>
  exec.rootOp({
    helper: ['remove-passphrase'],
    fallback: [{ command: 'security', args: ['delete-generic-password', '-s', PASSPHRASE_SERVICE, '-a', 'devhost', SYSTEM_KEYCHAIN] }],
    reason: 'remove the work volume passphrase from the System keychain',
    allowFailure: true,
  });

/** Is the keychain item there? Its attributes only: the passphrase is never read here. */
export async function passphraseStored(exec: Executor): Promise<boolean> {
  return (await exec.query('security', ['find-generic-password', '-s', PASSPHRASE_SERVICE, '-a', 'devhost', SYSTEM_KEYCHAIN])).code === 0;
}

export const unlockPlistInstalled = async (exec: Executor): Promise<boolean> => (await exec.readText(join(launchDaemonsDir(), `${UNLOCK_LABEL}.plist`))) !== null;
